def sheet(name, headers, widths, required):
    ws = wb.create_sheet(name)
    for i,(h,w) in enumerate(zip(headers,widths),1):
        c = ws.cell(row=1, column=i, value=h + (' *' if h in required else ''))
        c.font = Font(name=F, bold=True); c.fill = REQ_FILL if h in required else HEAD_FILL
        c.alignment = Alignment(vertical='center', wrap_text=True); c.border = Border(bottom=thin)
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = 'A2'; ws.row_dimensions[1].height = 32
    return ws

def put(ws, rows, date_cols=()):
    for r in rows:
        ws.append(r)
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.font = Font(name=F)
            if c.column in date_cols and c.value is not None: c.number_format = 'DD.MM.YYYY'
    ws.auto_filter.ref = ws.dimensions

def dv(ws, col, options, n=2000):
    v = DataValidation(type='list', formula1='"' + ','.join(options) + '"', allow_blank=True)
    v.error = 'Выберите значение из списка'; ws.add_data_validation(v); v.add(f'{col}2:{col}{n}')

